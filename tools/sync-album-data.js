const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const jsonPath = path.join(root, "album-data.json");
const jsPath = path.join(root, "album-data.js");

const jsonText = fs.readFileSync(jsonPath, "utf8").trimEnd();
const output = `// Generated from album-data.json. Do not edit this file manually.\nwindow.__ALBUM_DATA__ = ${jsonText}\n;\n`;

fs.writeFileSync(jsPath, output, "utf8");
console.log(`Synced ${path.basename(jsPath)} from ${path.basename(jsonPath)}`);
